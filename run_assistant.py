class TrustSphereRequestHandler(BaseHTTPRequestHandler):
    """Handles HTTP requests for the TrustSphere AI Assistant platform."""

    def log_message(self, format, *args):
        # Concise logging
        logger.info(f"{self.command} {self.path} - {args[1] if len(args) > 1 else ''}")

    def do_GET(self):
        parsed = urllib.parse.urlparse(self.path)
        path = parsed.path

        if path in ("/", "/index.html"):
            self.serve_main_page()
        elif path == "/api/status":
            self.send_json_response({
                "status": "ready",
                "diagnosis_loaded": current_diagnosis is not None,
                "product_title": current_diagnosis.product_title if current_diagnosis else ""
            })
        elif path == "/api/diagnosis":
            if current_diagnosis:
                # Generate charts
                p = current_diagnosis.pricing_analysis
                c_price = report_generator.visualizer.generate_price_corridor_chart(
                    p.listing_price, p.claimed_mrp, p.genuine_market_corridor_min,
                    p.genuine_market_corridor_max, p.corridor_median,
                    p.genuine_market_corridor_min * 0.72, current_diagnosis.product_title
                )
                aspect_dict = current_diagnosis.review_summary.get("aspect_findings", {}) if current_diagnosis.review_summary else {}
                c_aspect = report_generator.visualizer.generate_aspect_sentiment_chart(aspect_dict)
                c_radar = report_generator.visualizer.generate_multimodal_radar_chart(
                    {"Price Realism": 25.0 if p.is_price_suspicious else 90.0, "Review Trust": 25.0, "Visual Quality": 45.0, "Packaging Compliance": 20.0, "Seller Authenticity": 30.0},
                    {"Price Realism": 85.0, "Review Trust": 88.0, "Visual Quality": 92.0, "Packaging Compliance": 95.0, "Seller Authenticity": 90.0}
                )
                c_defects = report_generator.visualizer.generate_defect_distribution_chart(current_diagnosis.identified_gaps)

                diag_dict = asdict(current_diagnosis)
                diag_dict["charts"] = {
                    "price_corridor": c_price,
                    "aspect_sentiment": c_aspect,
                    "radar": c_radar,
                    "defect_distribution": c_defects
                }
                self.send_json_response(diag_dict)
            else:
                self.send_json_response({"error": "No diagnosis available"}, status=404)
        elif path == "/download-report":
            report_path = REPORTS_DIR / "latest_intelligence_report.html"
            if report_path.exists():
                with open(report_path, "rb") as f:
                    content = f.read()
                self.send_response(200)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Disposition", "inline; filename=TrustSphere_Product_Intelligence_Report.html")
                self.send_header("Content-Length", str(len(content)))
                self.end_headers()
                self.wfile.write(content)
            else:
                self.send_error(404, "Report not yet generated")
        else:
            self.send_error(404, "Not Found")

    def do_POST(self):
        parsed = urllib.parse.urlparse(self.path)
        path = parsed.path

        content_length = int(self.headers.get("Content-Length", 0))
        body = self.rfile.read(content_length)

        try:
            data = json.loads(body.decode("utf-8")) if body else {}
        except Exception:
            data = {}

        global current_diagnosis, active_report_html

        if path == "/api/analyze":
            title = data.get("product_title", "Nike Men's Revolution 6 Running Shoes")
            brand = data.get("brand", "Nike")
            marketplace = data.get("marketplace", "Flipkart")
            price = float(data.get("listing_price", 1500.0))
            mrp = float(data.get("claimed_mrp", 3000.0))
            reviews = data.get("reviews", None)

            current_diagnosis = assistant.analyze_product_query(
                product_title=title,
                brand=brand,
                marketplace=marketplace,
                listing_price=price,
                claimed_mrp=mrp,
                sample_reviews=reviews
            )

            active_report_html = report_generator.generate_html_report(
                current_diagnosis,
                output_file_path=str(REPORTS_DIR / "latest_intelligence_report.html")
            )

            self.send_json_response({
                "status": "success",
                "message": "Analysis completed successfully",
                "trust_score": current_diagnosis.overall_trust_score,
                "risk_tier": current_diagnosis.risk_tier,
                "gaps_count": len(current_diagnosis.identified_gaps)
            })

        elif path == "/api/chat":
            user_msg = data.get("message", "")
            response = assistant.respond_to_user_chat(user_msg, current_diagnosis)
            self.send_json_response(response)
        else:
            self.send_error(404, "Not Found")

    def send_json_response(self, data: Any, status: int = 200):
        body = json.dumps(data).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

