"""
acquire_nlp_benchmark.py
------------------------
Acquires and validates the Ott et al. Deceptive Opinion Spam benchmark corpus
(ACL 2011, EMNLP 2013) for text stylometry and deceptive NLP modeling.

Outputs:
- data/raw/benchmarks/deceptive_opinion_spam.csv
- data/raw/benchmarks/deceptive_opinion_spam.parquet
- data/raw/benchmarks/README.md
"""

import os
import logging
import subprocess
import pandas as pd

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")

BENCHMARK_DIR = "data/raw/benchmarks"
CSV_PATH = os.path.join(BENCHMARK_DIR, "deceptive_opinion_spam.csv")
PARQUET_PATH = os.path.join(BENCHMARK_DIR, "deceptive_opinion_spam.parquet")
README_PATH = os.path.join(BENCHMARK_DIR, "README.md")
SOURCE_URL = "https://raw.githubusercontent.com/rajsiddarth/Text_Analytics/master/deceptive-opinion.csv"


def acquire_benchmark() -> None:
    os.makedirs(BENCHMARK_DIR, exist_ok=True)
    logging.info("Acquiring Ott et al. Deceptive Opinion Spam corpus...")

    # Download using curl
    if not os.path.exists(CSV_PATH):
        cmd = ["curl.exe", "-s", "--max-time", "30", SOURCE_URL, "-o", CSV_PATH]
        logging.info("Executing download command: %s", " ".join(cmd))
        subprocess.run(cmd, check=True)

    # Validate downloaded dataset
    df = pd.read_csv(CSV_PATH)
    logging.info("Downloaded benchmark successfully. Shape: %s", df.shape)

    expected_cols = ["deceptive", "hotel", "polarity", "source", "text"]
    assert all(c in df.columns for c in expected_cols), f"Missing expected columns! Found: {list(df.columns)}"
    assert len(df) == 1600, f"Expected 1,600 rows, found {len(df)}"

    # Check class balance
    deceptive_counts = df["deceptive"].value_counts().to_dict()
    polarity_counts = df["polarity"].value_counts().to_dict()
    logging.info("Class distribution (deceptive): %s", deceptive_counts)
    logging.info("Class distribution (polarity): %s", polarity_counts)

    assert deceptive_counts.get("truthful") == 800 and deceptive_counts.get("deceptive") == 800
    assert polarity_counts.get("positive") == 800 and polarity_counts.get("negative") == 800

    # Save parquet version
    df.to_parquet(PARQUET_PATH, index=False)
    logging.info("Saved parquet benchmark to %s", PARQUET_PATH)

    # Write documentation README
    readme_content = """# Deceptive Opinion Spam Benchmark Corpus

## Provenance & Citations
This benchmark corpus originates from foundational NLP research by Myle Ott, Yejin Choi, Claire Cardie, and Jeffrey T. Hancock:

1. **ACL 2011:** *Finding Deceptive Opinion Spam by Any Stretch of the Imagination*. Proceedings of the 49th Annual Meeting of the Association for Computational Linguistics.
2. **NAACL/EMNLP 2013:** *Negative Deceptive Opinion Spam*. Proceedings of the 2013 Conference of the North American Chapter of the Association for Computational Linguistics.

## Dataset Specifications
- **Total Records:** 1,600 balanced reviews
- **Truthful Reviews:** 800 genuine reviews collected from TripAdvisor, Expedia, Hotels.com, Orbitz, Priceline, and Yelp.
- **Deceptive Reviews:** 800 crowdsourced deceptive reviews generated by Amazon Mechanical Turk workers instructed to write realistic but fraudulent reviews.
- **Polarity Breakdown:** 800 positive sentiment reviews, 800 negative sentiment reviews.
- **Entities:** 20 prominent hotels in the Chicago area (80 reviews per hotel).

## Schema
| Column | Type | Description |
|---|---|---|
| `deceptive` | string | Ground-truth label: `'truthful'` or `'deceptive'` |
| `hotel` | string | Hotel name identifier (20 unique hotels) |
| `polarity` | string | Sentiment polarity: `'positive'` or `'negative'` |
| `source` | string | Origin platform (e.g., `'TripAdvisor'`, `'MTurk'`, `'Web'`) |
| `text` | string | Full body text of the review |

## Purpose in AI Marketplace Analyzer
Used strictly as an **external NLP benchmark** to train, validate, and evaluate text stylometry, n-gram, and linguistic deception detection models against genuine experimental ground truth.

## Explicit Domain Limitations
1. **Domain Mismatch:** This corpus contains hotel reviews, whereas our primary dataset contains physical marketplace goods (cosmetics/beauty).
2. **Writing Styles:** Crowdsourced deceptive reviews generated on Mechanical Turk may exhibit stylistic differences compared to commercial e-commerce review rings.
3. **Non-Equivalence:** Amazon marketplace reviews must NEVER be automatically categorized as fraudulent based on classifiers trained on this dataset without transparent confidence calibration and multi-signal corroboration.
"""
    with open(README_PATH, "w", encoding="utf-8") as f:
        f.write(readme_content)
    logging.info("Saved benchmark documentation to %s", README_PATH)
    logging.info("NLP benchmark acquisition complete.")


if __name__ == "__main__":
    acquire_benchmark()
